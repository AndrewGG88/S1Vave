"""S1Vave's fixed-point tables (the chip has no FPU): tools/gen_tables.py -> firmware/gen/obv_tables.h
(committed, so a build needs no regeneration). FS = 44100, control rate every CTL = 16 frames."""
import math
import sys
from pathlib import Path

FS = 44100
CTL = 16


def arr(name, ctype, vals, per=10):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def k_block(tau_s):
    """one-pole coefficient per control block, Q24: level += (target - level) * k >> 24"""
    return max(1, min((1 << 24) - 1, int(round((1 << 24) * (1 - math.exp(-CTL / (tau_s * FS)))))))


def main(path):
    L = ["/* generated by tools/gen_tables.py: do not edit */", "#pragma once", "#include <stdint.h>",
         f"#define CTL {CTL}u", ""]
    # pitch: one octave of phase steps for MIDI 120..131 (C9..B9), lower octaves shift right
    L += arr("INC_C9", "uint32_t", [int(440.0 * 2 ** ((n - 69) / 12) / FS * 2 ** 32) for n in range(120, 132)], 6)
    # a semitone in 256 steps: 2^(i / 3072), Q16
    L += arr("FINE_Q16", "uint32_t", [int(round(65536 * 2 ** (i / 3072))) for i in range(256)])
    # SVF g = tan(pi f / fs) at integer semitones 0..136 (8.2 Hz .. 19.9 kHz), Q12, f capped at 0.45 fs
    fc = [min(440.0 * 2 ** ((n - 69) / 12), 0.45 * FS) for n in range(137)]
    L += arr("SVF_G", "uint16_t", [int(round(4096 * math.tan(math.pi * f / FS))) for f in fc])
    cut_hz = [int(round(f)) for f in fc]
    cut_hz[136] = 20000  # Display 20.0k when fully open
    L += arr("CUT_HZ", "uint16_t", cut_hz)
    # VCF Cutoff: Roland S-1 hardware-measured potentiometer taper (0..127 matching S-1 physical response)
    # Measured directly from physical S-1 audio analysis across CC 74:
    # Matches S-1 harmonic transmission: CC 48 ~73 Hz, CC 56 ~138 Hz, CC 64 ~277 Hz, CC 72 ~554 Hz
    cut_pts = [
        (0, 10.0),
        (16, 14.0),
        (32, 19.0),
        (40, 27.0),
        (48, 38.0),
        (56, 49.0),
        (64, 61.0),
        (72, 73.0),
        (80, 86.0),
        (88, 98.0),
        (96, 110.0),
        (112, 123.0),
        (127, 136.0)
    ]
    def interp_cut(x):
        if x <= cut_pts[0][0]: return cut_pts[0][1]
        if x >= cut_pts[-1][0]: return cut_pts[-1][1]
        for i in range(len(cut_pts) - 1):
            x0, y0 = cut_pts[i]
            x1, y1 = cut_pts[i + 1]
            if x0 <= x <= x1:
                t = (x - x0) / (x1 - x0)
                t = t * t * (3 - 2 * t)  # smoothstep monotonic interpolation
                return y0 + t * (y1 - y0)
        return cut_pts[-1][1]
    # Roland S-1 hardware-calibrated Cutoff Taper (power 3.60 curve up to 136.0 semitones = 20.0 kHz)
    cut_taper_warm = [int(round(256 * (10.0 + 126.0 * ((v / 127.0) ** 3.60)))) for v in range(128)]
    L += arr("CUTOFF_TAPER", "uint16_t", cut_taper_warm, 8)
    L += arr("CUTOFF_TAPER_WARM", "uint16_t", cut_taper_warm, 8)

    # Roland S-1 4-Pole Cascaded SVF Resonance Damping tables (0..127):
    # At Reso=0: 4-pole Butterworth maximally flat alignment (k1=7569, k2=3135)
    # At Reso=127: Authentic self-oscillation (k1=1000, k2=0)
    reso_k1 = [int(round(7569 - 6569 * (i / 127.0))) for i in range(128)]
    reso_k2 = [int(round(3135 * ((1.0 - (i / 127.0)) ** 1.35))) for i in range(128)]
    L += arr("RESO_K1", "uint16_t", reso_k1, 8)
    L += arr("RESO_K2", "uint16_t", reso_k2, 8)
    # tanh(x / 32768 * 2) * 32767 for x = i * 256 (sloopdx's softclip)
    L += arr("TANH_Q15", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    # Roland S-1 hardware-measured envelope times (calibrated directly against physical Roland S-1):
    # Attack: piecewise curve matching S-1 physical 10%-90% rise times (1.5 ms .. 2.780 s)
    # Mid-range (CC 10-20) calibrated slower to match S-1; fast attacks (CC 0-5) preserved
    attack_pts = [
        (0, 0.0015),
        (5, 0.0022),
        (10, 0.0120),
        (15, 0.0400),
        (20, 0.0650),
        (30, 0.100),
        (45, 0.220),
        (60, 0.440),
        (75, 0.750),
        (90, 1.150),
        (105, 1.890),
        (120, 2.480),
        (127, 2.780)
    ]
    def attack_time(v):
        if v <= attack_pts[0][0]: return attack_pts[0][1]
        for i in range(1, len(attack_pts)):
            if v <= attack_pts[i][0]:
                c0, t0 = attack_pts[i - 1]
                c1, t1 = attack_pts[i]
                return t0 + (v - c0) / (c1 - c0) * (t1 - t0)
        return attack_pts[-1][1]
    att_s = [attack_time(v) for v in range(128)]
    L += arr("ATT_MS_X10", "uint32_t", [int(round(s * 10000)) for s in att_s])
    L += arr("ENV_K_ATT", "uint32_t", [k_block(s / 0.9874) for s in att_s], 8)

    # Decay: hardware piecewise curve calibrated to Roland S-1 (20 ms .. 6.500 s)
    decay_pts = [
        (0, 0.020),
        (20, 0.220),
        (40, 0.500),
        (60, 1.010),
        (80, 1.580),
        (100, 2.800),
        (127, 6.500)
    ]
    def decay_time(v):
        if v <= decay_pts[0][0]: return decay_pts[0][1]
        for i in range(1, len(decay_pts)):
            if v <= decay_pts[i][0]:
                c0, t0 = decay_pts[i - 1]
                c1, t1 = decay_pts[i]
                return t0 + (v - c0) / (c1 - c0) * (t1 - t0)
        return decay_pts[-1][1]
    dec_s = [decay_time(v) for v in range(128)]
    L += arr("DEC_MS_X10", "uint32_t", [int(round(s * 10000)) for s in dec_s])
    L += arr("ENV_K_DEC", "uint32_t", [k_block(s / 2.3026) for s in dec_s], 8)

    # Release: hardware piecewise curve calibrated to Roland S-1 (10 ms .. 5.750 s)
    release_pts = [
        (0, 0.010),
        (20, 0.170),
        (40, 0.480),
        (60, 1.090),
        (80, 1.720),
        (100, 3.120),
        (127, 5.750)
    ]
    def release_time(v):
        if v <= release_pts[0][0]: return release_pts[0][1]
        for i in range(1, len(release_pts)):
            if v <= release_pts[i][0]:
                c0, t0 = release_pts[i - 1]
                c1, t1 = release_pts[i]
                return t0 + (v - c0) / (c1 - c0) * (t1 - t0)
        return release_pts[-1][1]
    rel_s = [release_time(v) for v in range(128)]
    L += arr("REL_MS_X10", "uint32_t", [int(round(s * 10000)) for s in rel_s])
    L += arr("ENV_K_REL", "uint32_t", [k_block(s / 2.3026) for s in rel_s], 8)

    # Legacy alias
    L += arr("TIME_MS_X10", "uint32_t", [int(round(s * 10000)) for s in dec_s])
    # glide 0 = off, else 5 ms .. 5 s to 95 % of the way, Q16 per block
    gms = [5.0 * (1000 ** (v / 127)) for v in range(128)]
    L += arr("GLIDE_MS", "uint16_t", [int(round(m)) for m in gms])
    L += arr("GLIDE_K", "uint16_t", [max(1, min(65535, int(round(65536 * (1 - math.exp(-CTL / (m / 3000 * FS)))))))
                                     for m in gms])
    # LFO 0.3 .. 35.8 Hz: Roland S-1 hardware-calibrated rate curve (0.30 Hz at 0..24, 5.45 Hz at 64, 35.76 Hz at 127)
    hz_x100 = [30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 30, 31, 33, 36, 40, 45, 50, 56, 61, 67, 73, 80, 87, 95, 103, 112, 121, 130, 140, 150, 161, 173, 185, 198, 212, 227, 244, 262, 282, 302, 322, 343, 364, 385, 406, 428, 451, 474, 497, 521, 545, 570, 596, 622, 649, 677, 704, 731, 758, 785, 811, 838, 864, 891, 917, 944, 970, 996, 1023, 1050, 1076, 1102, 1129, 1156, 1182, 1208, 1234, 1260, 1286, 1312, 1339, 1366, 1394, 1422, 1451, 1480, 1510, 1540, 1571, 1603, 1636, 1669, 1703, 1736, 1771, 1809, 1848, 1892, 1939, 1991, 2048, 2110, 2178, 2252, 2333, 2420, 2515, 2623, 2749, 2890, 3046, 3213, 3391, 3576]
    inc = [467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 467479, 479526, 513098, 564336, 629384, 704386, 785484, 868821, 950541, 1036272, 1133384, 1240635, 1356783, 1480586, 1610801, 1746187, 1885500, 2030025, 2182381, 2343328, 2513625, 2694033, 2885312, 3088221, 3303521, 3539868, 3802380, 4086506, 4387696, 4701399, 5023065, 5348143, 5672083, 5998002, 6331919, 6673642, 7022976, 7379727, 7743701, 8114704, 8492543, 8881738, 9284776, 9698405, 10119374, 10544434, 10970333, 11393820, 11811647, 12225331, 12638620, 13051606, 13464379, 13877031, 14289652, 14702334, 15115168, 15528108, 15941048, 16353988, 16766929, 17179869, 17592809, 18005749, 18418689, 18828645, 19234337, 19638324, 20043163, 20451413, 20865633, 21288379, 21722211, 22163967, 22610134, 23062738, 23523803, 23995358, 24479426, 24978035, 25493211, 26012780, 26530543, 27057493, 27604622, 28182921, 28803381, 29476995, 30214754, 31024916, 31912352, 32882964, 33942659, 35097340, 36352914, 37715286, 39190359, 40872702, 42832550, 45039307, 47462381, 50071175, 52835096, 55723548]
    L += arr("LFO_HZ_X100", "uint16_t", hz_x100)
    L += arr("LFO_INC", "uint32_t", inc, 8)

    # Pitch LFO Depth: Roland S-1 hardware-measured curve (up to ±28.7 semitones at CC 127)
    depth = [0, 4, 9, 14, 18, 23, 28, 33, 38, 44, 49, 54, 59, 65, 70, 75, 81, 87, 93, 100, 108, 116, 125, 135, 145, 156, 167, 179, 191, 205, 218, 233, 248, 263, 280, 296, 314, 332, 350, 369, 389, 410, 433, 458, 484, 512, 542, 573, 606, 640, 675, 712, 750, 789, 828, 869, 910, 953, 996, 1039, 1083, 1128, 1175, 1224, 1275, 1327, 1381, 1437, 1494, 1553, 1614, 1676, 1740, 1805, 1872, 1940, 2009, 2080, 2153, 2226, 2301, 2379, 2460, 2545, 2633, 2725, 2819, 2916, 3015, 3116, 3219, 3324, 3429, 3536, 3643, 3751, 3859, 3967, 4075, 4182, 4288, 4394, 4500, 4608, 4715, 4823, 4932, 5042, 5152, 5262, 5373, 5485, 5597, 5710, 5824, 5938, 6053, 6168, 6284, 6401, 6518, 6636, 6754, 6873, 6992, 7113, 7234, 7355]
    L += arr("LFO_PITCH_DEPTH", "uint16_t", depth, 8)
    # LFO delay / fade 0 .. 5 s in control blocks
    L += arr("LFO_DELAY_BLK", "uint16_t", [int(round((5000 * (v / 127) ** 2) / 1000 * FS / CTL)) for v in range(128)])
    # equal-power pan: gain Q12 for position 0..128 (sin), the other side reads it mirrored
    L += arr("PAN_Q12", "uint16_t", [int(round(4096 * math.sin(math.pi / 2 * i / 128))) for i in range(129)])
    # the knobs' arcs: cos in 5 degree steps, Q8
    L += arr("COS_Q8", "int16_t", [int(round(256 * math.cos(math.radians(5 * i)))) for i in range(72)], 12)
    Path(path).write_text("\n".join(L) + "\n")
    print(f"tables: {path}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "firmware/gen/obv_tables.h")
